from __future__ import annotations

from datetime import datetime

WEEKDAYS_RU = {
    0: "пн",
    1: "вт",
    2: "ср",
    3: "чт",
    4: "пт",
    5: "сб",
    6: "вс",
}


def format_date(date_iso: str) -> str:
    """'2026-09-30' -> '30.09 (ср)'."""
    dt = datetime.strptime(date_iso, "%Y-%m-%d")
    return f"{dt.strftime('%d.%m')} ({WEEKDAYS_RU[dt.weekday()]})"


